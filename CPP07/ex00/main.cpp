#include "whatever.hpp"
 
static void section(const std::string &title)
{
    std::cout << "\n============================================\n";
    std::cout << "  " << title << "\n";
    std::cout << "============================================\n\n";
}
 
int main(void)
{
    // -----------------------------------------------------------------------
    section("1. Subject example (int)");
    // -----------------------------------------------------------------------
    {
        int a = 2;
        int b = 3;
        ::swap(a, b);
        std::cout << "after swap(2, 3) -> a=" << a << " b=" << b << "\n";
        std::cout << "min(a, b) = " << ::min(a, b) << "\n";
        std::cout << "max(a, b) = " << ::max(a, b) << "\n";
    }
 
    // -----------------------------------------------------------------------
    section("2. Subject example (string)");
    // -----------------------------------------------------------------------
    {
        std::string c = "chaine1";
        std::string d = "chaine2";
        ::swap(c, d);
        std::cout << "after swap -> c=" << c << " d=" << d << "\n";
        std::cout << "min(c, d) = " << ::min(c, d) << "\n";
        std::cout << "max(c, d) = " << ::max(c, d) << "\n";
    }
 
    // -----------------------------------------------------------------------
    section("3. swap - equal values");
    // -----------------------------------------------------------------------
    {
        int a = 5;
        int b = 5;
        ::swap(a, b);
        std::cout << "swap(5, 5) -> a=" << a << " b=" << b << "\n";
        std::cout << "min(5, 5) = " << ::min(a, b) << "\n";
        std::cout << "max(5, 5) = " << ::max(a, b) << "\n";
    }
 
    // -----------------------------------------------------------------------
    section("4. negative integers");
    // -----------------------------------------------------------------------
    {
        int a = -10;
        int b = -3;
        std::cout << "min(-10, -3) = " << ::min(a, b) << "\n";
        std::cout << "max(-10, -3) = " << ::max(a, b) << "\n";
        ::swap(a, b);
        std::cout << "after swap   -> a=" << a << " b=" << b << "\n";
    }
 
    // -----------------------------------------------------------------------
    section("5. float");
    // -----------------------------------------------------------------------
    {
        float a = 1.5f;
        float b = 2.5f;
        std::cout << "min(1.5f, 2.5f) = " << ::min(a, b) << "\n";
        std::cout << "max(1.5f, 2.5f) = " << ::max(a, b) << "\n";
        ::swap(a, b);
        std::cout << "after swap      -> a=" << a << " b=" << b << "\n";
    }
 
    // -----------------------------------------------------------------------
    section("6. char");
    // -----------------------------------------------------------------------
    {
        char a = 'a';
        char b = 'z';
        std::cout << "min('a', 'z') = " << ::min(a, b) << "\n";
        std::cout << "max('a', 'z') = " << ::max(a, b) << "\n";
        ::swap(a, b);
        std::cout << "after swap   -> a=" << a << " b=" << b << "\n";
    }
 
    // -----------------------------------------------------------------------
    section("7. string - empty string edge case");
    // -----------------------------------------------------------------------
    {
        std::string a = "hello";
        std::string b = "";
        std::cout << "min(\"hello\", \"\") = \"" << ::min(a, b) << "\"\n";
        std::cout << "max(\"hello\", \"\") = \"" << ::max(a, b) << "\"\n";
        ::swap(a, b);
        std::cout << "after swap -> a=\"" << a << "\" b=\"" << b << "\"\n";
    }
 
    // -----------------------------------------------------------------------
    section("8. swap is symmetric (swap twice = original)");
    // -----------------------------------------------------------------------
    {
        int a = 7;
        int b = 13;
        ::swap(a, b);
        ::swap(a, b);
        if (a == 7 && b == 13)
            std::cout << "[OK] double swap restored original values\n";
        else
            std::cout << "[FAIL] double swap did not restore values\n";
    }
 
    std::cout << "\n";
    return 0;
}
